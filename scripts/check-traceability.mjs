#!/usr/bin/env node
/**
 * Build a traceability matrix from REQUIREMENTS.md → tests/**.
 *
 * Reads every `it('REQ-XXX-NNN[, REQ-...]: ...')` (and `test(...)`) title in
 * `tests/**.test.ts`, then writes `docs/traceability.md` mapping each
 * requirement ID to the tests that cite it.
 *
 * Exits non-zero when the `--strict` flag is passed and any requirement has
 * zero tests, or when an unknown ID is referenced from a test.
 *
 * Usage:
 *   node scripts/check-traceability.mjs           # generate, warn-only
 *   node scripts/check-traceability.mjs --strict  # fail on gaps (CI gate)
 */

import { execFileSync } from 'node:child_process';
import { readFileSync, readdirSync, statSync, writeFileSync, mkdirSync } from 'node:fs';
import { join, relative, sep } from 'node:path';
import { fileURLToPath } from 'node:url';

const repoRoot = join(fileURLToPath(import.meta.url), '..', '..');
const requirementsFile = join(repoRoot, 'REQUIREMENTS.md');
const testsDir = join(repoRoot, 'tests');
const outputFile = join(repoRoot, 'docs', 'traceability.md');

const strict = process.argv.includes('--strict');

const ID_PATTERN = /\bREQ-[A-Z][A-Z0-9-]*[A-Z0-9]-\d{3}\b/g;

/** Parse all requirement IDs (and their one-line shall statements) from REQUIREMENTS.md. */
function parseRequirements() {
  const text = readFileSync(requirementsFile, 'utf8');
  const requirements = new Map();
  // Match lines like: "- **REQ-CORE-001** — `refreshDeps` SHALL ..."
  const lineRe = /^-\s*\*\*(REQ-[A-Z][A-Z0-9-]*[A-Z0-9]-\d{3})\*\*\s*[—-]\s*(.+)$/gm;
  let m;
  while ((m = lineRe.exec(text)) !== null) {
    requirements.set(m[1], m[2].trim());
  }
  return requirements;
}

/** Recursively walk `dir` collecting `.test.ts` file paths. */
function collectTestFiles(dir) {
  const out = [];
  for (const entry of readdirSync(dir)) {
    const full = join(dir, entry);
    const st = statSync(full);
    if (st.isDirectory()) {
      out.push(...collectTestFiles(full));
    } else if (entry.endsWith('.test.ts')) {
      out.push(full);
    }
  }
  return out;
}

/** Extract `{ ids[], title, file, line }` records for every it()/test() call. */
function extractTestTitles(file) {
  const text = readFileSync(file, 'utf8');
  const records = [];
  // Match it('...'), it("..."), test('...'), test("...") — single-line literals only.
  // Multiline / template-literal titles are not supported by design; we want simple
  // grep-friendly titles.
  const re = /\b(?:it|test)\s*(?:\.\w+)?\s*\(\s*(['"])((?:\\.|(?!\1).)*)\1/g;
  let m;
  while ((m = re.exec(text)) !== null) {
    const title = m[2];
    const ids = title.match(ID_PATTERN);
    if (!ids) continue;
    const before = text.slice(0, m.index);
    const line = before.split('\n').length;
    records.push({ ids, title, file, line });
  }
  return records;
}

function relPath(p) {
  return relative(repoRoot, p).split(sep).join('/');
}

function main() {
  const requirements = parseRequirements();
  if (requirements.size === 0) {
    console.error('No requirements parsed from REQUIREMENTS.md');
    process.exit(1);
  }

  const testFiles = collectTestFiles(testsDir);
  const reqToTests = new Map();
  for (const id of requirements.keys()) reqToTests.set(id, []);
  const unknownReferences = [];

  for (const file of testFiles) {
    const records = extractTestTitles(file);
    for (const rec of records) {
      for (const id of rec.ids) {
        if (!requirements.has(id)) {
          unknownReferences.push({ id, file: rec.file, line: rec.line, title: rec.title });
          continue;
        }
        reqToTests.get(id).push(rec);
      }
    }
  }

  // Build markdown
  const lines = [];
  lines.push('# Requirements Traceability Matrix');
  lines.push('');
  lines.push('_Auto-generated by `node scripts/check-traceability.mjs`. Do not edit._');
  lines.push('');
  lines.push(
    'Each row maps a requirement from [REQUIREMENTS.md](../REQUIREMENTS.md) to the tests ' +
      'that cite its ID in their `it()`/`test()` title.',
  );
  lines.push('');

  const totalReqs = requirements.size;
  const covered = [...reqToTests.values()].filter((arr) => arr.length > 0).length;
  const isDeprecated = (id) => /\(deprecated/i.test(requirements.get(id) ?? '');
  const uncovered = totalReqs - covered;
  lines.push(
    `**Coverage:** ${covered}/${totalReqs} requirements have at least one test (` +
      `${uncovered} uncovered).`,
  );
  lines.push('');

  lines.push('| Requirement | Tests | Statement |');
  lines.push('| --- | --- | --- |');
  for (const [id, statement] of requirements) {
    const tests = reqToTests.get(id);
    const cell =
      tests.length === 0
        ? '_no tests_'
        : tests
            .map((t) => `[\`${t.title.replace(/\|/g, '\\|')}\`](../${relPath(t.file)}#L${t.line})`)
            .join('<br>');
    const statementCell = statement.replace(/\|/g, '\\|');
    lines.push(`| \`${id}\` | ${cell} | ${statementCell} |`);
  }
  lines.push('');

  if (unknownReferences.length > 0) {
    lines.push('## Unknown requirement IDs referenced by tests');
    lines.push('');
    for (const u of unknownReferences) {
      lines.push(
        `- \`${u.id}\` in [${relPath(u.file)}:${u.line}](../${relPath(u.file)}#L${u.line}) — \`${u.title}\``,
      );
    }
    lines.push('');
  }

  mkdirSync(join(repoRoot, 'docs'), { recursive: true });
  writeFileSync(outputFile, lines.join('\n'), 'utf8');
  try {
    execFileSync('pnpm', ['exec', 'prettier', '--write', outputFile], {
      cwd: repoRoot,
      stdio: 'ignore',
    });
  } catch {
    // Prettier unavailable or failed — leave the file as-is.
  }
  console.log(`Wrote ${relPath(outputFile)} (${covered}/${totalReqs} covered).`);

  if (uncovered > 0) {
    const missing = [...reqToTests.entries()]
      .filter(([, arr]) => arr.length === 0)
      .map(([id]) => id);
    const missingNonDeprecated = missing.filter((id) => !isDeprecated(id));
    const msg = `${uncovered} requirement(s) have no tests.`;
    if (strict && missingNonDeprecated.length > 0) {
      console.error(msg);
      for (const id of missingNonDeprecated) console.error(`  - ${id}`);
      process.exit(2);
    } else if (strict) {
      console.warn(
        `${uncovered} requirement(s) have no tests (all marked deprecated — ignored under --strict).`,
      );
    } else {
      console.warn(msg + ' (warn-only — pass --strict to fail)');
    }
  }
  if (unknownReferences.length > 0) {
    const msg = `${unknownReferences.length} unknown requirement reference(s) in tests.`;
    if (strict) {
      console.error(msg);
      process.exit(3);
    } else {
      console.warn(msg);
    }
  }
}

main();
